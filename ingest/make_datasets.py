"""Write one ERDDAP dataset description per Seaglider mission and level that is
live on ERDDAP, into erddap-config/datasets.d/.

    python ingest/make_datasets.py            # write/refresh datasets.d/*.xml
    python ingest/make_datasets.py --check    # only report what would change

How ERDDAP uses these: each file in datasets.d is one bare <dataset> block;
the axiom ERDDAP image joins them into its real datasets.xml when the
container starts. ERDDAP then serves each dataset straight from its NetCDF
file on the server (/data/ogdp/processed/<L1|L2>/<name>/<name>_<level>.nc,
where batch_push.py put it).

Dataset id (decided 2026-10-12): <std_mission_name>_l1 / _l2, e.g.
sg559_naco_lofoten_jul2012_l2 -- it becomes part of the public URL, so once a
dataset is published its id must not change, even if the mission's name is
later corrected in OGDB. Enforced via OGDB: once --set-urls has stored a
dataset's URL (dataset_processing.erddap_l1_url / erddap_l2_url), the id is
taken from that URL from then on, not recomputed from the name.

--set-urls (after deploying to the server): for every dataset, checks the
public ERDDAP URL actually answers, then stores it in OGDB -- the portal's
"NorGliders ERDDAP L1/L2" links. A dataset that doesn't answer yet (not
deployed, still loading) is reported and its URL left alone.

Why built per file, not from fixed templates: missions carry different
sensors -- among the 40 newer-layout L2 files only 33 variables are in all of
them and 68 more (oxygen, optics, derived quantities) are in some. So each
dataset lists exactly the variables in its own file, read locally (the
NetCDF must be reachable under projectsRoot, as for ingest.py). What IS
shared per file layout is in LAYOUTS below: which dimensions hold the data,
and fixes ERDDAP needs that the files lack -- the older layout (missions
001-011) gives times as bare "seconds" (epoch only in a `reference` note) and
latitude/longitude as "Decimal degrees" with non-standard names.

ERDDAP structure: EDDTableFromMultidimNcFiles -- one table row per
measurement (L1) or per profile x depth bin (L2), with per-profile time and
position repeated along the profile. cdm_data_type Trajectory, with a
constant `trajectory` column = the mission name (cf_role trajectory_id).

Global metadata: the files carry the instrument maker's (APL-UW / NOAA NODC
creator, references, titles) -- replaced with the facility's and the
mission's from OGDB.

A file that would break or mislead ERDDAP is skipped with a reason, e.g. an
L1 whose time values are unusable (mission 098 at the time of writing).
Generated files start with GENERATED_MARK; a generated file whose dataset is
no longer live is removed. Hand-written files in datasets.d are never touched.
"""

from __future__ import annotations

import argparse
import math
import os
import re
import sys

import requests
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

import numpy as np
from netCDF4 import Dataset

from config import load_config
from gateway_client import GatewayClient, GatewayError
from ingest import fail

DATASETS_D = Path(__file__).resolve().parent.parent / "erddap-config" / "datasets.d"
GENERATED_MARK = "<!-- GENERATED by ingest/make_datasets.py. Do not edit by hand; re-run it instead. (No double hyphens in XML comments: invalid XML.) -->"
EPOCH = "seconds since 1970-01-01T00:00:00Z"
INSTITUTION = "University of Bergen, Ocean Glider Facility"
INFO_URL = "https://ogf.uib.no"

# Per file layout: the dimension sets whose variables go into the table
# (outer dimension first), and the source names of time/latitude/longitude/
# depth. ERDDAP requires exactly those destination names for a Trajectory.
LAYOUTS = {
    "L1": {"dims": [("sg_data_point",)],
           "time": "time", "lat": "latitude", "lon": "longitude", "depth": "depth"},
    "L2_new": {"dims": [("profile",), ("depth",), ("profile", "depth")],
               "time": "time", "lat": "latitude", "lon": "longitude", "depth": "depth"},
    "L2_old": {"dims": [("time",), ("depth",), ("time", "depth")],
               "time": "time", "lat": "latitude", "lon": "longitude", "depth": "depth"},
}
DIMENSIONS_CSV = {"L1": "sg_data_point", "L2_new": "profile,depth", "L2_old": "time,depth"}

NUMPY_TO_ERDDAP = {"float32": "float", "float64": "double", "int8": "byte", "int16": "short",
                   "int32": "int", "int64": "long", "uint8": "ubyte", "uint16": "ushort", "uint32": "uint"}

# ERDDAP requires an ioos_category per variable; first matching keyword wins.
IOOS_RULES = [
    (("_qc",), "Quality"),
    (("dive_number", "trajectory"), "Identifier"),
    (("time", "year", "month", "date", "hour", "dd"), "Time"),
    (("latitude", "longitude", "depth", "lat", "lon"), "Location"),
    (("oxygen", "o2", "aa4330", "optode"), "Dissolved O2"),
    (("wlbb2fl", "fluor", "chl", "backscatter", "bb2", "sig470", "sig695", "sig700"), "Optical Properties"),
    (("curr", "speed", "vert_speed", "horz_speed"), "Currents"),
    (("salin", "conductivity", "sigma", "density", "gsw"), "Salinity"),
    (("temp", "theta"), "Temperature"),
    (("pressure", "pres"), "Pressure"),
    (("sound",), "Physical Oceanography"),
    (("eng_",), "Other"),
]


def ioos_category(name: str) -> str:
    low = name.lower()
    for keys, cat in IOOS_RULES:
        if any(k in low for k in keys):
            return cat
    return "Unknown"


def layout_of(ds, level: str) -> str:
    if level == "L1":
        return "L1"
    return "L2_new" if "profile" in ds.dimensions else "L2_old"


def time_problem(ds, name: str, layout: str) -> str | None:
    """Unusable time values make ERDDAP fail or serve nonsense -- check first."""
    if name not in ds.variables:
        return f"no `{name}` variable"
    v = np.ma.filled(ds[name][:].astype("float64"), np.nan)
    v = v[np.isfinite(v)]
    if v.size == 0:
        return "time has no valid values"
    lo, hi = float(v.min()), float(v.max())
    if lo < 3.15e8 or hi > 2.1e9:  # 1980 .. 2036 in epoch seconds
        return f"time values out of range ({lo:.3g} .. {hi:.3g} s since 1970) -- corrupted"
    return None


def var_block(ds, name: str, layout: str, roles: dict) -> str | None:
    var = ds[name]
    dtype = NUMPY_TO_ERDDAP.get(str(var.dtype))
    if dtype is None:
        return None  # char/string arrays: not on the table's dimensions anyway
    dest = {roles["time"]: "time", roles["lat"]: "latitude", roles["lon"]: "longitude",
            roles["depth"]: "depth"}.get(name, name)
    atts = {"ioos_category": ioos_category(dest)}
    units = str(getattr(var, "units", ""))
    if units.strip().lower() == "seconds" and "1970" in str(getattr(var, "reference", "")):
        atts["units"] = EPOCH  # older layout: epoch stated only in `reference`
    elif units.startswith("seconds since 1970") and dest == "time":
        atts["units"] = EPOCH
    if units.strip() == "C":
        atts["units"] = "degree_C"  # older layout; not a recognised unit string
    if dest.startswith("salinity") and units.strip().lower() in ("", "none"):
        atts["units"] = "1e-3"  # older layout says "none"; newer files use 1e-3
    if dest == "time":
        atts.update({"standard_name": "time", "units": EPOCH})
    elif dest == "latitude":
        atts.update({"standard_name": "latitude", "units": "degrees_north"})
    elif dest == "longitude":
        atts.update({"standard_name": "longitude", "units": "degrees_east"})
    elif dest == "depth":
        atts.update({"standard_name": "depth", "units": "m", "positive": "down"})
    if not getattr(var, "long_name", None):
        atts["long_name"] = str(getattr(var, "description", "") or getattr(var, "comment", "") or name)[:120]
    att_xml = "\n".join(f"            <att name={quoteattr(k)}>{escape(v)}</att>" for k, v in atts.items())
    return (f"    <dataVariable>\n        <sourceName>{escape(name)}</sourceName>\n"
            f"        <destinationName>{escape(dest)}</destinationName>\n        <dataType>{dtype}</dataType>\n"
            f"        <addAttributes>\n{att_xml}\n        </addAttributes>\n    </dataVariable>")


def mission_text(m: dict, level: str, stage: str) -> tuple[str, str]:
    when = (m.get("launchDate") or "")[:7]
    where = ", ".join(x for x in (m.get("project"), m.get("site")) if x)
    glider = (m.get("glider") or "").upper()
    kind = "timeseries (L1)" if level == "L1" else "profiles (L2)"
    stage_text = {"BASESTATION": "basestation processing during the mission",
                  "AUTO_QC": "post-mission reprocessing with automatic QC",
                  "MANUAL_QC": "post-mission reprocessing with automatic and manual QC"}.get(stage, stage)
    title = f"Seaglider {glider} {where} {when} -- {kind}"
    summary = (f"Seaglider {glider} mission {m['missionNumber']} ({m['stdMissionName']}), {where}, "
               f"{(m.get('launchDate') or '?')[:10]} to {(m.get('recoveryDate') or '?')[:10]}. "
               f"{'Measurements along the glider path' if level == 'L1' else 'Binned up and down profiles'} "
               f"from {stage_text}. Operated by the {INSTITUTION}.")
    return title, summary


def dataset_id_for(m: dict, level: str, live: dict) -> str:
    """The published id if OGDB already has the dataset's URL (frozen),
    otherwise the naming rule <std_mission_name>_<level>."""
    stored = live.get(f"erddap{level}Url") or ""
    found = re.search(r"/tabledap/([A-Za-z][A-Za-z0-9_]*)\.html", stored)
    return found.group(1) if found else f"{m['stdMissionName'].lower()}_{level.lower()}"


def dataset_xml(m: dict, level: str, stage: str, local_path: str, dataset_id: str) -> tuple[str | None, str]:
    """-> (xml or None, note). note explains a skip."""
    name = m["stdMissionName"].lower()  # = the folder batch_push uploads into
    with Dataset(local_path) as ds:
        layout = layout_of(ds, level)
        roles = LAYOUTS[layout]
        problem = time_problem(ds, roles["time"], layout)
        if problem:
            return None, f"skipped -- {problem}"
        missing = [r for r in ("lat", "lon", "depth") if roles[r] not in ds.variables]
        if missing:
            return None, f"skipped -- no {', '.join(roles[r] for r in missing)} variable"
        allowed = set(LAYOUTS[layout]["dims"])
        first = [roles["time"], roles["lat"], roles["lon"], roles["depth"]]
        names = first + sorted(v for v in ds.variables if ds[v].dimensions in allowed and v not in first)
        blocks = [b for b in (var_block(ds, v, layout, roles) for v in names) if b]
    title, summary = mission_text(m, level, stage)
    g = {
        "cdm_data_type": "Trajectory", "featureType": "trajectory",
        "cdm_trajectory_variables": "trajectory", "subsetVariables": "trajectory",
        "Conventions": "CF-1.10, ACDD-1.3", "title": title, "summary": summary,
        "institution": INSTITUTION, "infoUrl": INFO_URL, "sourceUrl": "(local files)",
        "creator_name": INSTITUTION, "creator_url": INFO_URL, "creator_type": "institution",
        "platform": "glider", "ogdb_mission_number": str(m["missionNumber"]), "ogdb_processing_stage": stage,
        # instrument maker's metadata carried in the files -- not ours to publish as-is
        "references": "null", "uuid": "null", "id": "null", "Metadata_Conventions": "null",
    }
    g_xml = "\n".join(f"        <att name={quoteattr(k)}>{escape(v)}</att>" for k, v in g.items())
    # Fixed-value column: ERDDAP needs the value as a JSON-style string, i.e.
    # in double quotes -- without them the column comes out empty (seen in
    # the first deployment test, 2026-10-12).
    trajectory = (f"    <dataVariable>\n        <sourceName>=&quot;{escape(name)}&quot;</sourceName>\n"
                  f"        <destinationName>trajectory</destinationName>\n        <dataType>String</dataType>\n"
                  f"        <addAttributes>\n            <att name=\"cf_role\">trajectory_id</att>\n"
                  f"            <att name=\"ioos_category\">Identifier</att>\n"
                  f"            <att name=\"long_name\">Mission</att>\n        </addAttributes>\n    </dataVariable>")
    xml = f"""{GENERATED_MARK}
<!-- Mission {m['missionNumber']} {name}, {level}, layout {layout}, stage {stage}. Source file in OGDB: see erddap_pushes / mission_erddap_status. -->
<dataset type="EDDTableFromMultidimNcFiles" datasetID={quoteattr(dataset_id)} active="true">
    <reloadEveryNMinutes>10080</reloadEveryNMinutes>
    <fileDir>/data/ogdp/processed/{level}/{escape(name)}/</fileDir>
    <fileNameRegex>{escape(name)}_{level}\\.nc</fileNameRegex>
    <recursive>false</recursive>
    <pathRegex>.*</pathRegex>
    <metadataFrom>last</metadataFrom>
    <standardizeWhat>0</standardizeWhat>
    <removeMVRows>true</removeMVRows>
    <sortFilesBySourceNames></sortFilesBySourceNames>
    <fileTableInMemory>false</fileTableInMemory>
    <addAttributes>
{g_xml}
    </addAttributes>
{trajectory}
{chr(10).join(blocks)}
</dataset>
"""
    return xml, f"{layout}, {len(blocks)} variables"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report what would change, write nothing")
    parser.add_argument("--mission", type=int, action="append", metavar="NUMBER", help="only this mission (repeatable)")
    parser.add_argument("--set-urls", action="store_true",
                        help="after deploying: store each answering dataset's public URL in OGDB (portal links)")
    args = parser.parse_args()
    try:
        config = load_config()
    except (FileNotFoundError, ValueError) as e:
        fail(str(e))
    client = GatewayClient(base_url=config["gateway_url"])
    try:
        client.login(config["service_email"], config["service_password"])
        missions = client.list_missions()
    except GatewayError as e:
        fail(str(e))

    wanted = set(args.mission or [])
    keep, written, unchanged, skipped, urls_set, not_answering = set(), [], [], [], [], []
    for m in sorted(missions, key=lambda m: m["missionNumber"]):
        if not (m.get("bestL1File") or m.get("bestL2File")) or (wanted and m["missionNumber"] not in wanted):
            continue
        live = client.get_dataset_detail(m["id"])
        for level in ("L1", "L2"):
            live_file, stage = live.get(f"erddap{level}File"), live.get(f"erddap{level}Status")
            if not live_file or not m.get("stdMissionName"):
                continue  # nothing on ERDDAP for this level -> no dataset
            label = f"{m['missionNumber']:03d} {m['stdMissionName'].lower()} {level}"
            dataset_id = dataset_id_for(m, level, live)
            xml, note = dataset_xml(m, level, stage, os.path.join(config["projects_root"], live_file), dataset_id)
            if xml is None:
                skipped.append((label, note))
                print(f"{label}: {note}")
                continue
            path = DATASETS_D / f"{dataset_id}.xml"
            keep.add(path.name)
            if path.exists() and path.read_text() == xml:
                unchanged.append(label)
            else:
                if not args.check:
                    DATASETS_D.mkdir(parents=True, exist_ok=True)
                    path.write_text(xml)
                written.append(label)
                print(f"{label}: {'would write' if args.check else 'wrote'} {path.name} ({note})")

            if args.set_urls:
                url = f"{config['erddap_url']}/tabledap/{dataset_id}.html"
                if live.get(f"erddap{level}Url") == url:
                    continue
                try:
                    answers = requests.get(f"{config['erddap_url']}/tabledap/{dataset_id}.das", timeout=60).status_code == 200
                except requests.RequestException:
                    answers = False
                if not answers:
                    not_answering.append(label)
                    print(f"{label}: URL not stored -- {dataset_id} doesn't answer on ERDDAP yet (deployed? still loading?)")
                    continue
                if not args.check:
                    try:
                        client.set_erddap_url(m["id"], level, url)
                    except GatewayError as e:
                        not_answering.append(label)
                        print(f"{label}: URL not stored -- {e}")
                        continue
                urls_set.append(label)
                print(f"{label}: {'would store' if args.check else 'stored'} {url}")

    removed = []
    if not wanted:  # only prune on a full run
        for p in sorted(DATASETS_D.glob("*.xml")):
            if p.name not in keep and p.read_text().startswith(GENERATED_MARK):
                removed.append(p.name)
                if not args.check:
                    p.unlink()
                print(f"{p.name}: {'would remove' if args.check else 'removed'} (no longer live)")

    print()
    print(f"{len(written)} {'to write' if args.check else 'written'}, {len(unchanged)} unchanged, "
          f"{len(skipped)} skipped, {len(removed)} {'to remove' if args.check else 'removed'}")
    for label, note in skipped:
        print(f"  SKIPPED {label}: {note}")
    if args.set_urls:
        print(f"ERDDAP URLs {'to store' if args.check else 'stored'} in OGDB: {len(urls_set)}, "
              f"not answering yet: {len(not_answering)}")


if __name__ == "__main__":
    main()
